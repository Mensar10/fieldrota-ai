"""Make the FieldRota web app work when index.html is opened straight from disk (file://).

Browsers block fetch() and canvas pixel reads for local files, so we:
  1. copy the trained policies (ai/*.json) into app/ai/
  2. pack every JSON the app fetches (regions, map outlines, AI policies) and the globe
     texture into app/embedded.js, which a plain <script> tag can load from disk
  3. pack each pilot satellite image into app/img_js/<name>.js, loaded only when the user
     clicks a field (automatic field outline)
  4. add a tiny fetch() shim to index.html that serves those embedded files first
Over http(s) (GitHub Pages, a local server) the app behaves exactly as before.
"""
import base64, glob, json, os, shutil, sys

APP = sys.argv[1] if len(sys.argv) > 1 else "app"
ROOT = os.path.dirname(os.path.abspath(__file__))
os.chdir(os.path.join(ROOT, "..") if os.path.basename(ROOT) == "tools" else ROOT)

# 1) policies
os.makedirs(f"{APP}/ai", exist_ok=True)
for p in glob.glob("ai/*.json"):
    shutil.copy(p, f"{APP}/ai/")

# 2) embedded JSON + globe texture
emb = {"json": {}, "img": {}}
for sub in ("regions", "geo", "ai"):
    for p in sorted(glob.glob(f"{APP}/{sub}/*.json")):
        with open(p, encoding="utf-8") as f:
            emb["json"][f"{sub}/{os.path.basename(p)}"] = json.load(f)
for p in [f"{APP}/img/bm/globe.jpg"] + sorted(glob.glob(f"{APP}/img/thumb/*.jpg")):
    with open(p, "rb") as f:
        emb["img"][os.path.relpath(p, APP).replace(os.sep, "/")] = "data:image/jpeg;base64," + base64.b64encode(f.read()).decode()
with open(f"{APP}/embedded.js", "w", encoding="utf-8") as f:
    f.write("/* generated by build_app.py: data for opening index.html straight from disk */\n")
    f.write("window.FR_EMBED=" + json.dumps(emb, ensure_ascii=False, separators=(",", ":")) + ";\n")

# 3) pilot satellite images, one small loader file each
os.makedirs(f"{APP}/img_js", exist_ok=True)
for p in sorted(glob.glob(f"{APP}/img/*.jpg")):
    name = os.path.basename(p)
    with open(p, "rb") as f:
        uri = "data:image/jpeg;base64," + base64.b64encode(f.read()).decode()
    with open(f"{APP}/img_js/{name}.js", "w") as f:
        f.write(f'(window.FR_IMGDATA=window.FR_IMGDATA||{{}})["img/{name}"]="{uri}";\n')

# 4) shim + two one-line hooks in index.html (idempotent)
SHIM = """<script src="embedded.js"></script>
<script>
/* FR-SHIM: serve embedded data when the page is opened from disk (see build_app.py) */
(function(){
  const E=window.FR_EMBED||{json:{},img:{}}, f0=window.fetch.bind(window), FILE=location.protocol==="file:";
  window.fetch=function(u,o){ const k=String(u).replace(/^\\.\\//,"");
    return E.json[k]?Promise.resolve(new Response(JSON.stringify(E.json[k]),{status:200,headers:{"Content-Type":"application/json"}})):f0(u,o); };
  window.FR_IMG=k=>FILE&&E.img[k]?E.img[k]:k;
  window.FR_IMG_ASYNC=k=>new Promise(res=>{ if(!FILE) return res(k); const D=window.FR_IMGDATA||{}; if(D[k]) return res(D[k]);
    const s=document.createElement("script"); s.src="img_js/"+k.replace(/^img\\//,"")+".js";
    s.onload=()=>res((window.FR_IMGDATA||{})[k]||k); s.onerror=()=>res(k); document.head.appendChild(s); });
})();
</script>
"""
html_path = f"{APP}/index.html"
src_path = "tools/index.src.html"  # the app with section 5, before packing
s = open(src_path, encoding="utf-8").read()
if "FR-SHIM" not in s:
    anchor = '<script src="lib/topojson-client.min.js"></script>\n'
    assert anchor in s
    s = s.replace(anchor, anchor + SHIM, 1)
    a, b = "e.img.src=src;", "e.img.src=FR_IMG(src);"
    assert s.count(a) == 1; s = s.replace(a, b)
    a, b = "im.onerror=rej; im.src=T.src; });", "im.onerror=rej; FR_IMG_ASYNC(T.src).then(u=>{im.src=u;}); });"
    assert s.count(a) == 1; s = s.replace(a, b)
    a, b = '<img src="img/thumb/${P.key}.jpg"', '<img src="${FR_IMG(`img/thumb/${P.key}.jpg`)}"'
    assert s.count(a) == 1; s = s.replace(a, b)
    # inline d3, topojson-client and the embedded data, so the page still works when
    # index.html is opened on its own (e.g. straight from inside a zip file)
    for tag, path in [('<script src="lib/d3.min.js"></script>', f"{APP}/lib/d3.min.js"),
                      ('<script src="lib/topojson-client.min.js"></script>', f"{APP}/lib/topojson-client.min.js"),
                      ('<script src="embedded.js"></script>', f"{APP}/embedded.js")]:
        code = open(path, encoding="utf-8").read().replace("</script", "<\\/script")
        assert s.count(tag) == 1, tag
        s = s.replace(tag, f"<script>/* inlined from {os.path.relpath(path, APP)} */\n{code}\n</script>")
    open(html_path, "w", encoding="utf-8").write(s)
    os.remove(f"{APP}/embedded.js")  # now inside index.html

# 5) Windows double-click launcher for a local server (optional)
with open(f"{APP}/start_local_server.bat", "w", newline="\r\n") as f:
    f.write("@echo off\r\ncd /d %~dp0\r\nstart \"\" http://localhost:8000/index.html\r\npython -m http.server 8000\r\n")
print("app ready:", html_path, f"{os.path.getsize(html_path)/1e6:.1f} MB")
